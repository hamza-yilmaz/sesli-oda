// Geçersiz girdide null döner.
export function cleanText(v, max) {
  if (typeof v !== 'string') return null;
  const s = v.replace(/[\u0000-\u001f\u007f​-‏‪-‮⁦-⁩]/g, '').replace(/\s+/g, ' ').trim();
  return s ? s.slice(0, max) : null;
}

export function cleanRoomName(v) {
  const s = cleanText(v, 32);
  if (!s) return null;
  return s.toLocaleLowerCase('tr').replace(/[^a-z0-9çğıöşü_-]+/g, '-').replace(/^-+|-+$/g, '') || null;
}

// Basit jeton kovası: saniyede `rate` jeton, en fazla `burst`.
export function makeLimiter(rate, burst) {
  let tokens = burst;
  let last = performance.now();
  return () => {
    const now = performance.now();
    tokens = Math.min(burst, tokens + ((now - last) / 1000) * rate);
    last = now;
    if (tokens < 1) return false;
    tokens -= 1;
    return true;
  };
}

export const store = {
  get(key, fallback) {
    try {
      const v = localStorage.getItem(key);
      return v === null ? fallback : JSON.parse(v);
    } catch {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch {
      /* gizli pencere vb. */
    }
  },
};

export async function sha256Hex(text) {
  const buf = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

export function initials(name) {
  const parts = (name || '?').trim().split(/\s+/).filter(Boolean);
  const s = parts.length > 1 ? parts[0][0] + parts[parts.length - 1][0] : (parts[0] || '?').slice(0, 2);
  return s.toLocaleUpperCase('tr');
}

// İsimden kararlı bir renk tonu üretir.
export function hueFor(id) {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % 360;
}

export function timeStr(d = new Date()) {
  return d.toLocaleTimeString('tr-TR', {hour: '2-digit', minute: '2-digit'});
}

